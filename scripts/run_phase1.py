"""Phase 1: data snapshot, quality checks, dataset, chronological split, baselines.

Usage:  python scripts/run_phase1.py [--refresh]
Writes reports/phase1_report.md and reports/phase1_*.csv.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tslaf.baselines import train_mean_forecast, zero_forecast  # noqa: E402
from tslaf.config import load_config  # noqa: E402
from tslaf.data import get_prices, load_metadata  # noqa: E402
from tslaf.features import build_dataset, feature_columns  # noqa: E402
from tslaf.metrics import evaluate  # noqa: E402
from tslaf.quality import run_quality_checks  # noqa: E402
from tslaf.split import chronological_split, fit_scaler, transform  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download instead of using the snapshot")
    args = ap.parse_args()

    cfg = load_config()
    prices = get_prices(cfg, refresh=args.refresh)
    meta = load_metadata(cfg.cache_path)
    t = cfg.target_ticker

    qr = run_quality_checks(prices, t, cfg.known_splits, cfg.extreme_return_abs, cfg.split_ratio_tolerance)
    if not qr.passed:
        print("WARNING: quality checks did not all pass; see report.")

    data = build_dataset(prices, cfg)
    cols = feature_columns(data)
    sp = chronological_split(data, cfg.train_frac, cfg.val_frac)

    scaler = fit_scaler(sp.train[cols])
    val_scaled = transform(scaler, sp.val[cols])
    test_scaled = transform(scaler, sp.test[cols])

    rows = []
    for name, part in (("val", sp.val), ("test", sp.test)):
        for model, y_hat in (("zero (random walk)", zero_forecast(part)),
                             ("train mean", train_mean_forecast(sp.train, part))):
            rows.append({"set": name, "model": model, **evaluate(part, y_hat)})
    results = pd.DataFrame(rows)

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    results.to_csv(out / "phase1_baselines.csv", index=False, float_format="%.6f")
    sp.summary().to_csv(out / "phase1_split.csv", index=False)

    desc = data[cols].describe().T[["mean", "std", "min", "max"]]
    target_stats = {name: part["target"].describe() for name, part in
                    (("train", sp.train), ("val", sp.val), ("test", sp.test))}
    ts = pd.DataFrame(target_stats).T[["count", "mean", "std", "min", "max"]]
    ts["up_share"] = [float((p["target"] > 0).mean()) for p in (sp.train, sp.val, sp.test)]

    fmt = results.copy()
    for c in ("ret_rmse", "ret_oos_r2_vs_zero", "hit_rate", "price_r2"):
        fmt[c] = fmt[c].map(lambda x: "n/a" if pd.isna(x) else f"{x:.4f}")
    for c in ("price_rmse", "price_mae"):
        fmt[c] = fmt[c].map(lambda x: f"{x:.3f}")

    lines = [
        "# Phase 1 report: data, features, split, baselines",
        "",
        "Generated by `scripts/run_phase1.py` from the snapshot below. All numbers are script output.",
        "",
        "## Data snapshot",
        "",
        f"- Source: {meta['source']} {meta.get('yfinance_version', '')}, auto_adjust={meta['auto_adjust']}",
        f"- Rows: {meta['rows']} trading days, {meta['first_date']} to {meta['last_date']}",
        f"- Columns: {', '.join(meta['columns'])}",
        f"- SHA-256: `{meta['sha256']}`",
        f"- Yahoo split record for {t}: {meta.get('yahoo_splits')}",
        "",
        "## Quality checks",
        "",
        f"- Missing values: {qr.n_missing}; non-positive prices: {qr.non_positive_prices}; "
        f"High/Low inconsistencies: {qr.high_low_violations}",
        f"- Days flagged (|return| > {cfg.extreme_return_abs:.0%} or within {cfg.split_ratio_tolerance:.0%} "
        f"of a split's mechanical return): {len(qr.flagged_days)}",
        f"- All checks passed: {qr.passed}",
        "",
        "Return on each known split date (an unadjusted series would show -80% / -66.7%):",
        "",
        qr.split_day_returns.assign(**{"return": qr.split_day_returns["return"].map(lambda x: f"{x:+.2%}")})
        .to_markdown(index=False),
        "",
        "Ten largest absolute daily moves (for manual review):",
        "",
        qr.largest_moves.assign(**{"return": qr.largest_moves["return"].map(lambda x: f"{x:+.2%}")})
        .rename_axis("date").reset_index().assign(date=lambda d: d["date"].dt.date).to_markdown(index=False),
        "",
        "## Dataset",
        "",
        f"- Usable rows after dropping the warm-up and the last day: {len(data)}",
        f"- Features ({len(cols)}): {', '.join(cols)}",
        "- Target: next-day log return ln(C_{t+1}/C_t)",
        "",
        "## Chronological split (no shuffling)",
        "",
        sp.summary().to_markdown(index=False),
        "",
        "Target (next-day log return) by set:",
        "",
        ts.to_markdown(floatfmt=".5f"),
        "",
        "Scaler fitted on train only. Mean of scaled features (should be ~0 on train, not on val/test):",
        f"train 0 by construction; val {val_scaled.mean().abs().mean():.3f} (mean |column mean|); "
        f"test {test_scaled.mean().abs().mean():.3f}.",
        "",
        "## Baselines",
        "",
        fmt.to_markdown(index=False),
        "",
        "`ret_oos_r2_vs_zero` is 0 for the random walk by definition. Any later model needs a positive value "
        "here, and a significant one, to claim predictive power.",
        "",
        "## Feature summary (full usable sample, unscaled)",
        "",
        desc.to_markdown(floatfmt=".4f"),
        "",
    ]
    (out / "phase1_report.md").write_text("\n".join(lines), encoding="utf-8")
    print(sp.summary().to_string(index=False))
    print(results.to_string(index=False))
    print("quality passed:", qr.passed)


if __name__ == "__main__":
    main()
